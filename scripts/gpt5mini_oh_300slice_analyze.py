def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--data-dir",
        default=str(Path(__file__).resolve().parents[1] / "data" / "oh_portal"),
        help="OH portal data directory.",
    )
    parser.add_argument(
        "--results-dir",
        default=str(
            Path(__file__).resolve().parents[1]
            / "docs" / "active" / "leave-behind-prep" / "results"
        ),
        help="Directory to write the metrics + disagreement JSON.",
    )
    parser.add_argument(
        "--max-disagreement-examples", type=int, default=100,
        help="Cap on stable-disagreement examples emitted for eyeballing.",
    )
    args = parser.parse_args()

    data_dir = Path(args.data_dir)
    results_dir = Path(args.results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)

    sonnet, mini = assemble_extraction_set(data_dir)
    print(
        f"[analyze] {len(sonnet)} sonnet filings, "
        f"{len(mini)} mini filings (with all 3 runs)",
        file=sys.stderr,
    )

    common = sorted(set(sonnet) & set(mini))
    if not common:
        print(
            "[analyze] No report_ids have both Sonnet and 3-run mini outputs. "
            "Dispatch may not have completed; check extracted_openai/.",
            file=sys.stderr,
        )
        return 2

    metrics = aggregate_metrics(sonnet, mini)
    costs = aggregate_cost_and_wall(common, data_dir)

    metrics_out = {
        "headline": metrics["headline"],
        "by_field_type": metrics["by_field_type"],
        "cost_and_wall_clock": costs,
    }
    metrics_path = results_dir / "20260608_gpt5mini_oh_300slice_metrics.json"
    metrics_path.write_text(json.dumps(metrics_out, indent=2))
    print(f"[analyze] metrics -> {metrics_path}", file=sys.stderr)

    disagreements = metrics["stable_disagreements"]
    # Cap and shuffle would lose ordering; instead cap deterministically by
    # taking every Nth element to surface a spread of report_ids rather than
    # 100 from the first 5 reports.
    if len(disagreements) > args.max_disagreement_examples:
        step = max(1, len(disagreements) // args.max_disagreement_examples)
        disagreements = disagreements[::step][: args.max_disagreement_examples]
    disagree_path = (
        results_dir / "20260608_gpt5mini_oh_300slice_stable_disagreements.json"
    )
    disagree_path.write_text(json.dumps({
        "n_total_stable_disagreements": metrics["headline"][
            "stable_disagreement_rate"
        ] * metrics["headline"]["n_field_paths_compared"],
        "n_emitted": len(disagreements),
        "examples": disagreements,
    }, indent=2, default=str))
    print(f"[analyze] stable disagreements -> {disagree_path}", file=sys.stderr)

    print("\n========== HEADLINE ==========", file=sys.stderr)
    print(json.dumps(metrics["headline"], indent=2), file=sys.stderr)
    print("\n========== COST + WALL CLOCK ==========", file=sys.stderr)
    print(json.dumps(costs, indent=2), file=sys.stderr)

    # Pre-registered verdict from plan step 14.
    h = metrics["headline"]
    sigma = h["mini_sigma_noise"]
    stable = h["stable_disagreement_rate"]
    if sigma > 0.90 and stable < 0.10:
        verdict = (
            "plausibly viable, recommend follow-on hand-validation post-Fellowship"
        )
    elif sigma > 0.90 and stable < 0.25:
        verdict = (
            "viable on consistency, needs hand-judgment on disagreement "
            "category mix before commitment"
        )
    else:
        verdict = "not suitable at current setup; deeper investigation needed"
    print(f"\nPRE-REGISTERED VERDICT: {verdict}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
